/// A circuit's centre line: samples STEP apart round the loop, each with how sharply the line
/// turns there (radians per map pixel, + for left, smoothed).
pub struct Line {
    pub points: Vec<[f64; 2]>,
    pub curve: Vec<f64>,
    /// the start/finish line: its middle and the way the cars cross it
    pub start: (f64, f64, f64),
}

impl Line {
    pub fn new(control: &[[f64; 2]], start: (f64, f64, f64)) -> Line {
        let points = spline(control);
        let n = points.len();
        let span = 6;
        let mut raw = vec![0.0; n];
        for i in 0..n {
            let (a, b, c) = (points[(i + n - span) % n], points[i], points[(i + span) % n]);
            let mut d = (c[1] - b[1]).atan2(c[0] - b[0]) - (b[1] - a[1]).atan2(b[0] - a[0]);
            while d > std::f64::consts::PI {
                d -= 2.0 * std::f64::consts::PI;
            }
            while d < -std::f64::consts::PI {
                d += 2.0 * std::f64::consts::PI;
            }
            raw[i] = d / (dist(a, b) + dist(b, c)).max(1.0);
        }
        let curve = (0..n).map(|i| (-8..=8).map(|k| raw[(i as i64 + k).rem_euclid(n as i64) as usize]).sum::<f64>() / 17.0).collect();
        Line { points, curve, start }
    }

    pub fn for_map(id: &str) -> Line {
        let (control, start) = circuit(id).unwrap_or_else(|| panic!("no circuit for {id}"));
        Line::new(control, start)
    }

    /// the art pixel-sized checkered strip of the start/finish line: true if world (x, y) is on
    /// it, and which colour square (0 or 1)
    pub fn start_line(&self, x: f64, y: f64) -> Option<u8> {
        let (sx, sy, h) = self.start;
        let (f, r) = ([h.cos(), h.sin()], [h.sin(), -h.cos()]);
        let (dx, dy) = (x - sx, y - sy);
        let (along, across) = (dx * f[0] + dy * f[1], dx * r[0] + dy * r[1]);
        (along >= 0.0 && along < 24.0 && across.abs() < ROAD as f64 - 3.0)
            .then(|| (((across + ROAD as f64) / 6.0).floor() as i64 + (along / 6.0).floor() as i64).rem_euclid(2) as u8)
    }

    /// true near the start line (no lane markings painted there)
    pub fn near_start(&self, x: f64, y: f64) -> bool {
        dist([x, y], [self.start.0, self.start.1]) < 70.0
    }

    pub fn len(&self) -> usize {
        self.points.len()
    }

    /// the direction of travel at sample i (a unit vector)
    pub fn tangent(&self, i: usize) -> [f64; 2] {
        let n = self.len();
        let (a, b) = (self.points[(i + n - 1) % n], self.points[(i + 1) % n]);
        let l = dist(a, b).max(1e-9);
        [(b[0] - a[0]) / l, (b[1] - a[1]) / l]
    }

    /// the sample nearest to world point p
    pub fn nearest(&self, p: [f64; 2]) -> usize {
        (0..self.len()).min_by(|&a, &b| dist(self.points[a], p).total_cmp(&dist(self.points[b], p))).unwrap()
    }

    /// which samples lie on the stretch driven from the sample nearest `from` to the one
    /// nearest `to` (a named piece of road, like Lombard Street)
    pub fn stretch(&self, from: [f64; 2], to: [f64; 2]) -> Vec<bool> {
        let (n, a, b) = (self.len(), self.nearest(from), self.nearest(to));
        let mut on = vec![false; n];
        let mut i = a;
        loop {
            on[i] = true;
            if i == b {
                return on;
            }
            i = (i + 1) % n;
        }
    }

    /// the length of the lap
    pub fn length(&self) -> f64 {
        let n = self.len();
        (0..n).map(|i| dist(self.points[i], self.points[(i + 1) % n])).sum()
    }

    /// the waypoints the CPUs follow: the centre line, closer together through the corners,
    /// starting just past the line and ending on it
    pub fn waypoints(&self) -> Vec<(f32, f32)> {
        let n = self.len();
        let line = [self.start.0, self.start.1];
        let start = (0..n).min_by(|&a, &b| dist(self.points[a], line).total_cmp(&dist(self.points[b], line))).unwrap();
        let mut out = Vec::new();
        let mut acc = 0.0;
        for k in 1..=n {
            let (i, p) = ((start + k) % n, (start + k - 1) % n);
            acc += dist(self.points[i], self.points[p]);
            let spacing = if self.curve[i].abs() > 0.0009 { 40.0 } else { 80.0 };
            if acc >= spacing && k < n - 4 {
                out.push((self.points[i][0].round() as f32, self.points[i][1].round() as f32));
                acc = 0.0;
            }
        }
        out.push((self.start.0 as f32, self.start.1 as f32));
        out
    }

    /// where the 12 grid slots are (as crates/sim/src/maps.rs lines them up behind the line)
    pub fn grid(&self) -> Vec<[f64; 2]> {
        let (sx, sy, h) = self.start;
        let (f, r) = ([h.cos(), h.sin()], [h.sin(), -h.cos()]);
        (0..12)
            .map(|slot| {
                let (row, column) = ((slot / 3) as f64, slot % 3);
                let across = 165.0 + column as f64 * 36.0 + 5.0 - 200.0 - 6.0; // centred on the road
                let back = 276.0 - row * 30.0 - if column == 1 { 12.0 } else { 0.0 } + 10.0 - 300.0;
                [sx + r[0] * across + f[0] * back, sy + r[1] * across + f[1] * back]
            })
            .collect()
    }

    /// what's wrong with the shape: stretches too close for a wall between them (the road's
    /// edge, plus the sim's 12 of run-off each side, plus a wall), or too close to the edge
    pub fn problems(&self) -> Vec<String> {
        let n = self.len();
        let need = 2.0 * (ROAD as f64 + 1.0 + 12.0) + 14.0;
        let mut out: Vec<(f64, [f64; 2], [f64; 2])> = Vec::new();
        for i in (0..n).step_by(2) {
            for j in (i + 2..n).step_by(2) {
                let along = (j - i).min(n - (j - i)) as f64 * STEP;
                if along < need * 2.5 {
                    continue;
                }
                let d = dist(self.points[i], self.points[j]);
                if d < need {
                    let (a, b) = (self.points[i], self.points[j]);
                    match out.iter_mut().find(|c| dist(c.1, a) < 150.0) {
                        Some(c) if d < c.0 => *c = (d, a, b),
                        Some(_) => {}
                        None => out.push((d, a, b)),
                    }
                }
            }
        }
        let mut problems: Vec<String> = out
            .iter()
            .map(|(d, a, b)| format!("{d:.0} apart (need {need:.0}) between ({:.0}, {:.0}) and ({:.0}, {:.0})", a[0], a[1], b[0], b[1]))
            .collect();
        for (slot, g) in self.grid().iter().enumerate() {
            let d = (0..n).map(|i| dist(*g, self.points[i])).fold(f64::MAX, f64::min);
            if d > ROAD as f64 - 4.0 {
                problems.push(format!("grid slot {slot} at ({:.0}, {:.0}) is {d:.0} off the centre line", g[0], g[1]));
            }
        }
        let margin = ROAD as f64 + 20.0;
        for p in &self.points {
            if p[0] < margin || p[1] < margin || p[0] > W as f64 - margin || p[1] > H as f64 - margin {
                problems.push(format!("({:.0}, {:.0}) is within {margin:.0} of the edge", p[0], p[1]));
                break;
            }
        }
        problems
    }
}

/// How far every map pixel is from a centre line, worked out once, with which sample is
/// nearest and which side of the line the pixel is on (+1 left of travel).
pub struct Field {
    dist: Vec<f32>,
    near: Vec<u32>,
    side: Vec<i8>,
}

impl Field {
    pub fn new(line: &Line) -> Field {
        const BUCKET: i32 = 64;
        let (bw, bh) = (W / BUCKET + 1, H / BUCKET + 1);
        let n = line.len();
        let mut buckets = vec![Vec::new(); (bw * bh) as usize];
        for (i, p) in line.points.iter().enumerate() {
            let (cx, cy) = ((p[0] as i32 / BUCKET).clamp(0, bw - 1), (p[1] as i32 / BUCKET).clamp(0, bh - 1));
            buckets[(cy * bw + cx) as usize].push(i);
        }
        let size = (W * H) as usize;
        let mut field = Field { dist: vec![f32::MAX; size], near: vec![0; size], side: vec![1; size] };
        // only pixels within this many buckets of the line get a real distance (plenty for painting)
        let reach = 4;
        for y in 0..H {
            for x in 0..W {
                let (cx, cy) = (x / BUCKET, y / BUCKET);
                let (px, py) = (x as f64 + 0.5, y as f64 + 0.5);
                let (mut best, mut bi, mut side) = (f64::MAX, 0usize, 1i8);
                for gy in (cy - reach).max(0)..=(cy + reach).min(bh - 1) {
                    for gx in (cx - reach).max(0)..=(cx + reach).min(bw - 1) {
                        for &i in &buckets[(gy * bw + gx) as usize] {
                            let (a, b) = (line.points[i], line.points[(i + 1) % n]);
                            let (dx, dy) = (b[0] - a[0], b[1] - a[1]);
                            let l2 = dx * dx + dy * dy;
                            let t = if l2 == 0.0 { 0.0 } else { (((px - a[0]) * dx + (py - a[1]) * dy) / l2).clamp(0.0, 1.0) };
                            let (qx, qy) = (a[0] + dx * t - px, a[1] + dy * t - py);
                            let d = qx * qx + qy * qy;
                            if d < best {
                                best = d;
                                bi = i;
                                side = if dx * (py - a[1]) - dy * (px - a[0]) >= 0.0 { 1 } else { -1 };
                            }
                        }
                    }
                }
                let k = (y * W + x) as usize;
                if best < f64::MAX {
                    field.dist[k] = best.sqrt() as f32;
                    field.near[k] = bi as u32;
                    field.side[k] = side;
                }
            }
        }
        field
    }

    fn index(x: i32, y: i32) -> Option<usize> {
        (x >= 0 && y >= 0 && x < W && y < H).then(|| (y * W + x) as usize)
    }

    /// distance from the centre line to world pixel (x, y), rounded down (far away off the map)
    pub fn distance(&self, x: i32, y: i32) -> i32 {
        Field::index(x, y).map_or(i32::MAX / 2, |k| self.dist[k].min(1e6) as i32)
    }

    /// the nearest centre line sample to (x, y), and which side of the line it is (+1 left)
    pub fn nearest(&self, x: i32, y: i32) -> (usize, i32) {
        Field::index(x, y).map_or((0, 1), |k| (self.near[k] as usize, self.side[k] as i32))
    }
}

fn dist(a: [f64; 2], b: [f64; 2]) -> f64 {
    (a[0] - b[0]).hypot(a[1] - b[1])
}

/// a closed Catmull-Rom spline through the points, sampled about every STEP
fn spline(p: &[[f64; 2]]) -> Vec<[f64; 2]> {
    let n = p.len();
    let mut out = Vec::new();
    for i in 0..n {
        let (p0, p1, p2, p3) = (p[(i + n - 1) % n], p[i], p[(i + 1) % n], p[(i + 2) % n]);
        let k = ((dist(p1, p2) / STEP) as usize).max(2);
        for j in 0..k {
            let t = j as f64 / k as f64;
            let (t2, t3) = (t * t, t * t * t);
            let f = |a: f64, b: f64, c: f64, d: f64| 0.5 * (2.0 * b + (-a + c) * t + (2.0 * a - 5.0 * b + 4.0 * c - d) * t2 + (-a + 3.0 * b - 3.0 * c + d) * t3);
            out.push([f(p0[0], p1[0], p2[0], p3[0]), f(p0[1], p1[1], p2[1], p3[1])]);
        }
    }
    out
}

/// prints every circuit's waypoints (for crates/sim/src/maps.rs), length and problems
pub fn report() -> Result<(), String> {
    let mut bad = false;
    for id in IDS {
        let line = Line::for_map(id);
        let w = line.waypoints();
        let (sx, sy, h) = line.start;
        println!("{id}: lap {:.0}, {} waypoints, start ({sx:.1}, {sy:.1}, {h:.4})", line.length(), w.len());
        println!("{}", w.iter().map(|(x, y)| format!("({x:.1}, {y:.1})")).collect::<Vec<_>>().join(", "));
        for p in line.problems() {
            println!("  {p}");
            bad = true;
        }
    }
    if bad { Err("some circuits need fixing".into()) } else { Ok(()) }
}

